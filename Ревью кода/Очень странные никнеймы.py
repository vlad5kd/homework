s = input()
while len(s) < 10:  # строго < 10 вместо <= 10
    if len(s) % 4 == 0:  # остаток % 4 == 0 вместо // 4
        s = s + 'x'
    elif len(s) % 5 == 0:  # остаток % вместо //
        s = s + 'y'
    else:
        s = 'z' + s  # 'z' прибавляем слева, а не справа
s = '@' + s  # заменил '&' на '@'
print(s)