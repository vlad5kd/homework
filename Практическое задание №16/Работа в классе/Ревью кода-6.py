mx = -10**6 - 1  # взял число меньше минимально возможного вместо 0
s = 0
for i in range(10):  # 10 чисел вместо 11
    x = int(input())
    if x < 0:
        s += x  # прибавляем к сумме (+=), а не просто s = x
        if x > mx:  # сдвинул проверку максимума внутрь if x < 0
            mx = x
if s == 0:  # добавил проверку, если отрицательных вообще не было
    print('NO')
else:
    print(s)
    print(mx)